import os
import shutil
import stat

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
root = root.replace('\\', '/')
node_modules = os.path.join(root, 'node_modules')
package_lock = os.path.join(root, 'package-lock.json')

if os.path.isdir(node_modules):
    for dirpath, dirnames, filenames in os.walk(node_modules, topdown=False):
        for filename in filenames:
            path = os.path.join(dirpath, filename)
            try:
                os.chmod(path, stat.S_IWRITE)
                os.remove(path)
            except Exception as exc:
                print('FILE_FAIL', path, exc)
        for dirname in dirnames:
            path = os.path.join(dirpath, dirname)
            try:
                os.chmod(path, stat.S_IWRITE)
                os.rmdir(path)
            except Exception as exc:
                print('DIR_FAIL', path, exc)
    try:
        os.rmdir(node_modules)
        print('REMOVED node_modules')
    except Exception as exc:
        print('REMOVE_FAIL', node_modules, exc)
else:
    print('NO_NODE_MODULES')

if os.path.isfile(package_lock):
    try:
        os.chmod(package_lock, stat.S_IWRITE)
        os.remove(package_lock)
        print('REMOVED package-lock.json')
    except Exception as exc:
        print('PACKAGE_LOCK_FAIL', package_lock, exc)
else:
    print('NO_PACKAGE_LOCK')
